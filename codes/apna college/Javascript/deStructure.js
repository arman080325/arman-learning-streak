let name=["John","Jane","Jim","Jack","Jill"];

let [first,second,third]=name;
console.log(first,second,third);
//Here we are using destructuring assignment to assign the values of the array to the variables first, second and third. The first variable will be assigned the value of the first element of the array, the second variable will be assigned the value of the second element of the array and so on.
//Original array is not modified. It is just a way to extract values from an array and assign them to variables in a more concise way.
